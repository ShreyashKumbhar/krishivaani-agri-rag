        f"| Retrieval Precision@5 | {_pct(metrics['precision_at_5'])} | — | — | Document-level precision on the same cases |",
        f"| Answer faithfulness (lexical support) | {_pct(metrics['faithfulness'])} | 90% | {target_status['faithfulness']} | Transparent token-overlap check on answered RAG cases; not RAGAS/LLM-judge |",
        f"| Correct refusal rate | {_pct(metrics['correct_refusal_rate'])} | 90% | {target_status['correct_refusal_rate']} | Measured on {metrics['refusal_cases']} unanswerable/adversarial cases |",
        f"| Overall decision accuracy | {_pct(metrics['decision_accuracy'])} | — | — | Answer / ask-to-repeat / refuse compared with labels |",
        f"| Answer rate on answerable cases | {_pct(metrics['answer_rate_on_answerable'])} | — | — | Includes RAG and tool cases |",
        f"| Intent classification accuracy | {_pct(metrics['intent_accuracy'])} | — | — | Rule-based intent labels vs hand labels |",
        f"| Mean query latency | {metrics['latency_ms_mean']:.0f} ms | — | — | In-process pipeline latency, no network ASR/TTS |",
        f"| p50 query latency | {metrics['latency_ms_p50']:.0f} ms | — | — | In-process pipeline latency |",
        f"| p95 query latency | {metrics['latency_ms_p95']:.0f} ms | — | — | In-process pipeline latency |",
