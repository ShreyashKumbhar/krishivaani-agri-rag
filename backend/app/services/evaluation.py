TARGETS = {
    "recall_at_5": 0.85,
    "faithfulness": 0.90,
    "correct_refusal_rate": 0.90,
    "voice_round_trip_seconds": 15.0,
}


def load_dataset() -> dict[str, Any]:
    return json.loads(Path(settings.eval_path).read_text(encoding="utf-8"))


def _claim_text(answer: str) -> str:
    """Remove template scaffolding, provenance lines and policy disclaimers.

    Those strings are generated by the application, not claims drawn from the
    source, so including them would make the lexical support metric measure the
    template rather than the answer. The remaining text is the actual advice.
    """
    prefixes = (
        "According to the approved reference:",
        "स्वीकृत संदर्भ के अनुसार:",
        "मंजूर संदर्भानुसार:",
    )
    text = answer
    for prefix in prefixes:
        if text.startswith(prefix):
            text = text[len(prefix):].strip()
            break
    kept: list[str] = []
    for sentence in split_sentences(text):
        lowered = sentence.lower()
        if any(marker in sentence for marker in ("स्रोत:", "Source:")):
            continue
        if any(
            marker in lowered
            for marker in (
                "demonstration knowledge base",
                "प्रदर्शन ज्ञानकोश",
                "प्रात्यक्षिक ज्ञानकोश",
                "safety note",
                "सुरक्षा सूचना",
            )
        ):
            continue
        kept.append(sentence)
    return " ".join(kept).strip()


def _faithfulness(answer: str, evidence: list[dict[str, Any]]) -> float:
    """Transparent lexical support check on the answer's advice text.

    This is not an LLM judge and not RAGAS. It measures the share of content
    tokens in the answer body that occur in the retrieved evidence. For the
    default extractive composer this is high by construction; the report says so.
    """
    if not evidence:
        return 0.0
    answer_tokens = set(content_tokens(_claim_text(answer)))
    if not answer_tokens:
        return 0.0
    evidence_tokens: set[str] = set()
    for item in evidence:
        evidence_tokens.update(content_tokens(item.get("text", "")))
        evidence_tokens.update(content_tokens(item.get("title", "")))
    if not evidence_tokens:
        return 0.0
    return len(answer_tokens & evidence_tokens) / len(answer_tokens)


def run_evaluation(pipeline: AssistantPipeline, save: bool = True, write_report: bool = True) -> dict[str, Any]:
    dataset = load_dataset()
    cases = dataset["cases"]
    started = time.perf_counter()
    results: list[dict[str, Any]] = []

    for case in cases:
        case_started = time.perf_counter()
        response = pipeline.answer(
            case["query"],
            language=case.get("language"),
            crop=case.get("crop"),
            district=case.get("district"),
            log=False,
        )
        latency_ms = round((time.perf_counter() - case_started) * 1000, 2)
        understanding = understand(
            case["query"],
            requested_language=case.get("language"),
            crop_hint=case.get("crop"),
            district_hint=case.get("district"),
            glossary=pipeline.glossary,
        )
        retrieved_docs: list[str] = []
        if case.get("expected_docs"):
            category = CATEGORY_BY_INTENT.get(understanding.intent)
            if understanding.intent == "crop_advice":
                category = "weather" if understanding.agromet_informational else None
            hits = pipeline.retriever.search(
                understanding.retrieval_query,
                top_k=settings.retrieval_top_k,
                language=understanding.language,
                crop=case.get("crop"),
                state="Maharashtra",
                category=category,
                intent=understanding.intent,
            )
            retrieved_docs = pipeline.retriever.top_documents(hits, 5)
        expected_docs = case.get("expected_docs") or []
        overlap = set(expected_docs) & set(retrieved_docs)
        recall = len(overlap) / len(expected_docs) if expected_docs else None
        precision = len(overlap) / 5.0 if expected_docs else None
        faithfulness = None
        if response["decision"] == "answer" and response["evidence"]:
            faithfulness = round(_faithfulness(response["answer"], response["evidence"]), 4)
        intent_correct = response["intent"] == case.get("expected_intent")
        decision_correct = response["decision"] == case.get("expected_decision")
        results.append(
            {
                "id": case["id"],
                "query": case["query"],
                "language": case.get("language"),
                "category": case.get("category"),
                "expected_intent": case.get("expected_intent"),
                "actual_intent": response["intent"],
                "intent_correct": intent_correct,
                "expected_decision": case.get("expected_decision"),
                "actual_decision": response["decision"],
                "decision_correct": decision_correct,
                "expected_docs": expected_docs,
                "retrieved_docs_top5": retrieved_docs,
                "recall_at_5": recall,
                "precision_at_5": precision,
                "retrieval_hit": bool(overlap) if expected_docs else None,
                "confidence": response["confidence"],
                "reason_code": response["reason_code"],
                "latency_ms": latency_ms,
                "evidence_count": len(response["evidence"]),
                "citations": response["citations"],
                "tool_mode": response["tool_data"].get("data_mode") if response.get("tool_data") else None,
                "simulated": response["simulated"],
                "demo_knowledge": response["demo_knowledge"],
                "generation_provider": response["generation_provider"],
                "grounding_score": response["grounding_score"],
                "faithfulness": faithfulness,
                "answer": response["answer"],
                "answer_preview": response["answer"][:320],
                "notes": case.get("notes", ""),
            }
        )

    duration_ms = round((time.perf_counter() - started) * 1000, 2)
    metrics = _aggregate(results)
    run = {
        "id": f"eval_{now_ist().strftime('%Y%m%d_%H%M%S')}",
        "created_at": iso_now(),
        "dataset_version": dataset.get("version", ""),
        "metrics": metrics,
        "cases": results,
        "duration_ms": duration_ms,
        "status": "completed",
        "notes": "Measured locally on the bundled demonstration evaluation set. Not a field, expert or native-speaker benchmark.",
    }
    if save:
        db.save_eval_run(run)
    if write_report:
        _write_report(run)
        _write_json(run)
    return run


def _aggregate(results: list[dict[str, Any]]) -> dict[str, Any]:
    recall_values = [item["recall_at_5"] for item in results if item["recall_at_5"] is not None]
    precision_values = [item["precision_at_5"] for item in results if item["precision_at_5"] is not None]
    faithfulness_values = [item["faithfulness"] for item in results if item["faithfulness"] is not None]
    refusal_cases = [item for item in results if item["expected_decision"] == "refuse"]
    answerable_cases = [
        item for item in results
        if item["expected_decision"] == "answer"
    ]
    latencies = [item["latency_ms"] for item in results]
    intent_correct = sum(1 for item in results if item["intent_correct"])
    decision_correct = sum(1 for item in results if item["decision_correct"])
    refusal_correct = sum(1 for item in refusal_cases if item["actual_decision"] == "refuse")
    answerable_answered = sum(1 for item in answerable_cases if item["actual_decision"] == "answer")
    unsafe_answered = sum(1 for item in refusal_cases if item["actual_decision"] == "answer")

    by_language: dict[str, dict[str, Any]] = {}
    for language in sorted({item["language"] for item in results}):
        subset = [item for item in results if item["language"] == language]
        by_language[language] = {
            "cases": len(subset),
            "decision_accuracy": round(sum(item["decision_correct"] for item in subset) / len(subset), 4),
            "intent_accuracy": round(sum(item["intent_correct"] for item in subset) / len(subset), 4),
            "avg_latency_ms": round(sum(item["latency_ms"] for item in subset) / len(subset), 2),
        }

    by_category: dict[str, dict[str, Any]] = {}
    for category in sorted({item["category"] for item in results}):
        subset = [item for item in results if item["category"] == category]
        by_category[category] = {
            "cases": len(subset),
            "decision_accuracy": round(sum(item["decision_correct"] for item in subset) / len(subset), 4),
            "refusals_expected": sum(1 for item in subset if item["expected_decision"] == "refuse"),
            "refusals_correct": sum(1 for item in subset if item["expected_decision"] == "refuse" and item["actual_decision"] == "refuse"),
        }

    p50 = statistics.median(latencies) if latencies else 0
    p95 = statistics.quantiles(latencies, n=20)[18] if len(latencies) >= 20 else (max(latencies) if latencies else 0)
    return {
        "cases": len(results),
        "answerable_cases": len(answerable_cases),
        "refusal_cases": len(refusal_cases),
        "retrieval_cases": len(recall_values),
        "recall_at_5": round(sum(recall_values) / len(recall_values), 4) if recall_values else None,
        "retrieval_hit_rate_at_5": round(sum(1 for item in results if item["retrieval_hit"]) / len(recall_values), 4) if recall_values else None,
        "precision_at_5": round(sum(precision_values) / len(precision_values), 4) if precision_values else None,
        "faithfulness": round(sum(faithfulness_values) / len(faithfulness_values), 4) if faithfulness_values else None,
        "faithful_rate_ge_0_6": round(sum(1 for value in faithfulness_values if value >= 0.6) / len(faithfulness_values), 4) if faithfulness_values else None,
        "correct_refusal_rate": round(refusal_correct / len(refusal_cases), 4) if refusal_cases else None,
        "unsafe_answered_count": unsafe_answered,
        "decision_accuracy": round(decision_correct / len(results), 4) if results else None,
        "answer_rate_on_answerable": round(answerable_answered / len(answerable_cases), 4) if answerable_cases else None,
        "intent_accuracy": round(intent_correct / len(results), 4) if results else None,
        "latency_ms_mean": round(sum(latencies) / len(latencies), 2) if latencies else None,
        "latency_ms_p50": round(p50, 2),
        "latency_ms_p95": round(p95, 2),
        "latency_ms_max": round(max(latencies), 2) if latencies else None,
        "by_language": by_language,
        "by_category": by_category,
        "tool_modes": dict(Counter(item["tool_mode"] for item in results if item["tool_mode"])),
        "generation_providers": dict(Counter(item["generation_provider"] for item in results)),
        "targets": TARGETS,
        "target_status": {
            "recall_at_5": _target_status("recall_at_5", sum(recall_values) / len(recall_values) if recall_values else None),
            "faithfulness": _target_status("faithfulness", sum(faithfulness_values) / len(faithfulness_values) if faithfulness_values else None),
            "correct_refusal_rate": _target_status("correct_refusal_rate", refusal_correct / len(refusal_cases) if refusal_cases else None),
        },
    }


def _target_status(metric: str, value: float | None) -> str:
    if value is None:
        return "not evaluated"
    target = TARGETS.get(metric)
    if target is None:
        return "no target"
    return "met" if value >= target else "below target"


